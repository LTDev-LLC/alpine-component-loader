const createSkeletonDependencies = (calls = []) => ({
    async generateSkeletons(options, dependencies) {
        // Materialize deterministic generated output without launching a browser in unit tests
        const name = basename(dirname(options.outDir)),
            path = resolve(options.outDir, 'acl-skeletons.css'),
            component = `${name}-stage-component`;
        calls.push({
            dependencies,
            options,
        });
        await mkdir(options.outDir, { recursive: true });
        await writeFile(
            path,
            `/* Generated by alpine-component-loader skeleton. Do not edit. */\n${component}:not(:defined){display:block}\n`,
        );
        return {
            components: [component],
            failures: [],
            files: [path],
            mode: 'css',
            warnings: [],
        };
    },
    // Keep unit output quiet while retaining progress callback coverage
    onProgress() {},
});

const readImportMap = (source) => {
    // Decode the single import map from staged HTML
    const match = source.match(/<script\b[^>]*type=["']importmap["'][^>]*>([\s\S]*?)<\/script\s*>/i);
    if (!match) throw new TypeError('Import map not found.');
    return JSON.parse(match[1]);
};

const collectFiles = async (root, directory = root) => {
    // Collect deterministic content identities below one artifact root
    const files = [];
    // Visit every staged file in path order
    for (const entry of (await readdir(directory, { withFileTypes: true })).sort(
        // Compare staged paths in deterministic order
        (left, right) => left.name.localeCompare(right.name),
    )) {
        const path = join(directory, entry.name);
        if (entry.isDirectory()) files.push(...(await collectFiles(root, path)));
        else if (entry.isFile())
            files.push({
                path: relative(root, path),
                digest: createHash('sha256')
                    .update(await readFile(path))
                    .digest('hex'),
            });
    }
    return files;
};

test('staged package imports follow every browser distribution export', async () => {
    // Compare generated mappings with package distribution exports
    const imports = await createStagedPackageImports(),
        packageJson = JSON.parse(await readFile(resolve('package.json'), 'utf8')),
        expected = Object.fromEntries(
            Object.entries(packageJson.exports)
                .filter(
                    // Select exports backed by browser distribution files
                    ([, definition]) => definition?.import?.startsWith('./dist/'),
                )
                .map(
                    // Convert one package export to its public staged identity
                    ([subpath, definition]) => [
                        subpath === '.' ? packageJson.name : `${packageJson.name}${subpath.slice(1)}`,
                        `/${definition.import.slice(2).replace(/\.js$/, '.min.js')}`,
                    ],
                ),
        );
    assert.deepEqual(imports, expected);
});

test('staged import maps preserve application mappings and scopes', async () => {
    // Rewrite an application-owned import map
    const packageImports = await createStagedPackageImports(),
        source = `<!doctype html><html><head>
        <script type="importmap">{
            "imports": {
                "application": "/application.js",
                "alpine-component-loader": "/__acl_hmr/modules/index.min.js",
                "alpine-component-loader/old": "/old.js"
            },
            "scopes": { "/admin/": { "application": "/admin.js" } }
        }</script></head><body></body></html>`,
        transformed = updateStagedImportMap(source, packageImports),
        importMap = readImportMap(transformed);
    assert.equal(importMap.imports.application, '/application.js');
    assert.equal(importMap.imports['alpine-component-loader'], '/dist/index.min.js');
    assert.equal(importMap.imports['alpine-component-loader/old'], undefined);
    assert.deepEqual(importMap.scopes, { '/admin/': { application: '/admin.js' } });
    assert.deepEqual(
        Object.fromEntries(
            Object.entries(importMap.imports).filter(
                // Select the staged ACL package family
                ([specifier]) =>
                    specifier === 'alpine-component-loader' || specifier.startsWith('alpine-component-loader/'),
            ),
        ),
        packageImports,
    );
});

test('staged import maps are inserted and malformed or ambiguous maps fail', async () => {
    // Exercise insertion and invalid authored map diagnostics
    const packageImports = await createStagedPackageImports(),
        inserted = updateStagedImportMap(
            '<!doctype html><html><head><title>Example</title></head></html>',
            packageImports,
        );
    assert.deepEqual(readImportMap(inserted).imports, packageImports);
    assert.throws(
        // Reject malformed authored JSON
        () =>
            updateStagedImportMap('<html><head><script type="importmap">{bad}</script></head></html>', packageImports),
        /malformed/,
    );
    assert.throws(
        // Reject ambiguous multiple import maps
        () =>
            updateStagedImportMap(
                '<html><head><script type="importmap">{}</script><script type="importmap">{}</script></head></html>',
                packageImports,
            ),
        /more than one/,
    );
});

test('staged document bases remain nested across clean and index URL navigation', () => {
    // Insert and replace canonical nested bases without reserializing the page
    const source = '<!doctype html><html><head><title>Example</title></head><body></body></html>',
        inserted = updateStagedBaseHref(source, 'feature-lab'),
        existing = updateStagedBaseHref(
            '<!doctype html><html><head><base target="_self" href="../"><title>Example</title></head></html>',
            'a11y',
        ),
        missingHref = updateStagedBaseHref(
            '<!doctype html><html><head><base target="_self"><title>Example</title></head></html>',
            'offline',
        );
    assert.match(inserted, /<base href="\/examples\/feature-lab\/index\.html" data-acl-stage-base>/);
    assert.match(existing, /<base target="_self" href="\/examples\/a11y\/index\.html">/);
    assert.match(missingHref, /<base target="_self" href="\/examples\/offline\/index\.html">/);
    const base = 'https://static.example.test/examples/feature-lab/index.html';
    assert.equal(new URL('./styles.css', base).pathname, '/examples/feature-lab/styles.css');
    assert.equal(
        new URL('./components/shadow-card.html', base).pathname,
        '/examples/feature-lab/components/shadow-card.html',
    );
    assert.throws(
        // Reject ambiguous base URL ownership
        () =>
            updateStagedBaseHref(
                '<!doctype html><html><head><base href="/one/"><base href="/two/"></head></html>',
                'playground',
            ),
        /more than one base/,
    );
    assert.throws(
        // Reject documents that cannot safely receive the generated base
        () => updateStagedBaseHref('<!doctype html><html><body></body></html>', 'playground'),
        /explicit head/,
    );
});

