test('staging is reproducible and preserves existing output after a failure', async (context) => {
    // Compare repeated output and protect a prior artifact
    const temporaryRoot = await mkdtemp(join(tmpdir(), 'acl-stage-atomic-')),
        first = resolve(temporaryRoot, 'first'),
        second = resolve(temporaryRoot, 'second'),
        brokenRoot = resolve(temporaryRoot, 'broken'),
        protectedOutput = resolve(temporaryRoot, 'protected');
    context.after(async () => {
        // Release generated test artifacts
        await rm(temporaryRoot, {
            recursive: true,
            force: true,
        });
    });

    await stageExamples(
        {
            names: ['offline', 'playground', 'offline', 'a11y'],
            root: repositoryRoot,
            outputRoot: first,
        },
        createSkeletonDependencies(),
    );
    await stageExamples(
        {
            names: ['offline', 'playground', 'a11y'],
            root: repositoryRoot,
            outputRoot: second,
        },
        createSkeletonDependencies(),
    );
    assert.deepEqual(await collectFiles(first), await collectFiles(second));

    await mkdir(resolve(brokenRoot, 'examples/playground'), { recursive: true });
    await writeFile(
        resolve(brokenRoot, 'examples/playground/index.html'),
        `<!doctype html><html><head><script defer src="${alpineUrl}"></script></head></html>`,
    );
    await mkdir(protectedOutput);
    await writeFile(resolve(protectedOutput, 'marker.txt'), 'keep');
    await assert.rejects(
        stageExamples(
            {
                names: ['playground', 'ssr', 'a11y'],
                root: repositoryRoot,
                outputRoot: protectedOutput,
            },
            createSkeletonDependencies(),
        ),
        /SSR server/,
    );
    assert.equal(await readFile(resolve(protectedOutput, 'marker.txt'), 'utf8'), 'keep');
    await assert.rejects(
        stageExample(
            {
                name: 'playground',
                root: brokenRoot,
                outputRoot: protectedOutput,
            },
            createSkeletonDependencies(),
        ),
        /distribution is missing/,
    );
    assert.equal(await readFile(resolve(protectedOutput, 'marker.txt'), 'utf8'), 'keep');
    await assert.rejects(
        stageExamples(
            {
                names: ['playground'],
                root: repositoryRoot,
                outputRoot: protectedOutput,
            },
            {
                async generateSkeletons() {
                    // Simulate a browser-backed capture failure after temporary staging begins
                    throw new Error('capture failed');
                },
                // Suppress expected failure-test progress
                onProgress() {},
            },
        ),
        /capture failed/,
    );
    assert.equal(await readFile(resolve(protectedOutput, 'marker.txt'), 'utf8'), 'keep');
});
