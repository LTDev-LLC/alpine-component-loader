test('stage selection accepts static examples and rejects backend or unsafe targets', () => {
    // Exercise the complete selector allowlist
    staticExamples.forEach(
        // Accept every documented static example
        (name) => assert.equal(validateExampleName(name), name),
    );
    assert.equal(validateExampleName(), 'playground');
    assert.throws(
        // Reject the development-server example
        () => validateExampleName('hmr'),
        /development HMR server/,
    );
    assert.throws(
        // Reject the focused SSR example
        () => validateExampleName('ssr'),
        /SSR server/,
    );
    assert.throws(
        // Reject the SSR feature lab
        () => validateExampleName('feature-lab-ssr'),
        /SSR server/,
    );
    assert.throws(
        // Reject traversal disguised as a selector
        () => validateExampleName('../playground'),
        /Unknown static example/,
    );
    assert.throws(
        // Reject an explicit empty selector
        () => validateExampleName(''),
        /Unknown static example/,
    );
});

test('stage selections default, deduplicate, and retain first command-line order', () => {
    // Normalize empty, repeated, and reordered selector lists
    assert.deepEqual(normalizeExampleNames(), ['playground']);
    assert.deepEqual(normalizeExampleNames([]), ['playground']);
    assert.deepEqual(normalizeExampleNames(['offline', 'a11y', 'offline', 'playground', 'a11y']), [
        'offline',
        'a11y',
        'playground',
    ]);
    assert.deepEqual(normalizeExampleNames(['playground', 'feature-lab']), ['playground', 'feature-lab']);
    assert.deepEqual(normalizeExampleNames(['feature-lab', 'playground']), ['feature-lab', 'playground']);
    assert.throws(
        // Reject an invalid selection even when its neighbors are valid
        () => normalizeExampleNames(['a11y', '../offline', 'playground']),
        /Unknown static example/,
    );
    assert.throws(
        // Reject backend-dependent examples in a mixed list
        () => normalizeExampleNames(['offline', 'hmr']),
        /development HMR server/,
    );
    assert.throws(
        // Reject non-list internal input
        () => normalizeExampleNames('playground'),
        /must be an array/,
    );
});

