test('each supported example produces a direct-import-map static artifact', async (context) => {
    // Stage and inspect every supported example
    const temporaryRoot = await mkdtemp(join(tmpdir(), 'acl-stage-examples-'));
    context.after(async () => {
        // Release generated test artifacts
        await rm(temporaryRoot, {
            recursive: true,
            force: true,
        });
    });

    const calls = [],
        dependencies = createSkeletonDependencies(calls);
    // Verify each artifact through physical output files
    for (const name of staticExamples) {
        const outputRoot = resolve(temporaryRoot, name),
            result =
                name === 'a11y'
                    ? await stageExamples(
                          {
                              names: [name, name],
                              root: repositoryRoot,
                              outputRoot,
                          },
                          dependencies,
                      )
                    : await stageExample(
                          {
                              name,
                              root: repositoryRoot,
                              outputRoot,
                          },
                          dependencies,
                      );
        assert.deepEqual(result.examples, [name]);
        assert.equal(result.mode, 'redirect');
        const entry = await readFile(resolve(outputRoot, 'examples', name, 'index.html'), 'utf8'),
            importMap = readImportMap(entry);
        assert.match(entry, new RegExp(`<base href="/examples/${name}/index\\.html" data-acl-stage-base>`));
        assert.equal(importMap.imports['alpine-component-loader'], '/dist/index.min.js');
        assert.equal(importMap.imports['alpine-component-loader/testing/vitest'], '/dist/testing-vitest.min.js');
        assert.match(
            await readFile(resolve(outputRoot, 'index.html'), 'utf8'),
            new RegExp(`examples/${name}/index.html`),
        );
        assert.equal((await stat(resolve(outputRoot, 'dist/index.min.js'))).isFile(), true);
        assert.equal((await stat(resolve(outputRoot, 'examples', name, 'skeletons/acl-skeletons.css'))).isFile(), true);
        await assert.rejects(stat(resolve(outputRoot, 'node_modules')), /ENOENT/);
        await assert.rejects(stat(resolve(outputRoot, 'styles.css')), /ENOENT/);
        assert.doesNotMatch(entry, /\/__acl_hmr\/modules\//);
        assert.match(
            entry,
            /<link rel="stylesheet" href="\.\/skeletons\/acl-skeletons\.css" data-acl-stage-skeletons>/,
        );
    }
    assert.equal(calls.length, staticExamples.length);
    calls.forEach(({ dependencies: captureDependencies, options }) => {
        // Verify one normalized capture contract
        const name = basename(dirname(options.outDir));
        assert.equal(options.target.type, 'local');
        assert.equal(options.target.root.startsWith(temporaryRoot), true);
        assert.equal(options.target.index, join('examples', name, 'index.html'));
        assert.equal(options.mode, 'css');
        assert.equal(options.allowPartial, false);
        assert.equal(options.force, true);
        assert.deepEqual(options.viewports, {
            mobile: {
                width: 390,
                height: 844,
            },
            desktop: {
                width: 1440,
                height: 900,
            },
        });
        assert.equal(typeof captureDependencies.preparePage, 'function');
    });

    const offlineRoot = resolve(temporaryRoot, 'offline'),
        offlineManifest = JSON.parse(
            await readFile(resolve(offlineRoot, 'examples/offline/acl-precache-manifest.json'), 'utf8'),
        );
    assert.equal((await stat(resolve(offlineRoot, 'examples/offline/app.min.js'))).isFile(), true);
    assert.ok(
        offlineManifest.entries.some(
            // Require the exact remote Alpine runtime to be available after a successful install
            (entry) => entry.url === alpineUrl && entry.required === false,
        ),
    );
    assert.ok(
        offlineManifest.entries.some(
            // Precache the staged skeleton stylesheet for a complete offline reload
            (entry) => entry.url === '/examples/offline/skeletons/acl-skeletons.css' && entry.required === true,
        ),
    );
});

