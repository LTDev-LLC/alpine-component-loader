import { readFile, writeFile } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';
import { descriptors, optionDefaults } from './option-descriptors.mjs';
// Compile the basic data contract without runtime descriptor traversal
const literal = (value) => JSON.stringify(value, null, 4),
    sets = ['fetch', 'poll', 'cache-bound']
        .map(
            (reaction, index) =>
                `export const ${['DATA_FETCH_ATTRIBUTES', 'DATA_POLL_ATTRIBUTES', 'DATA_CACHE_BOUND_ATTRIBUTES'][index]} = new Set(${literal(descriptors.filter((item) => item.attribute && item.reaction === reaction).map((item) => item.attribute))});`,
        )
        .join('\n'),
    data = descriptors.filter((item) => item.group),
    reads = data
        .map(
            (item) =>
                `${item.group}: ${item.merge === 'fetchOptions' ? 'mergeFetchOptions(globalConfig.data?.options, localConfig.data?.options)' : `localConfig.data?.${item.group} ?? globalConfig.data?.${item.group} ?? DEFAULT_DATA_OPTIONS.${item.group}`}`,
        )
        .join(',\n'),
    values = await readFile(new URL('../src/runtime/values.js', import.meta.url), 'utf8'),
    merge =
        '// Merge request options while preserving header precedence\n' +
        values
            .slice(values.indexOf('export const mergeFetchOptions'), values.indexOf('// Flatten nested'))
            .replace('export const', 'const'),
    options = await readFile(new URL('./data-readers-template.js', import.meta.url), 'utf8'),
    readers = options.slice(
        options.indexOf('// Read boolean attributes'),
        options.indexOf('// Resolve one descriptor'),
    ),
    region = `// BEGIN GENERATED DATA CONTRACT\n// Compiled from authoritative option descriptors\nexport const DEFAULT_DATA_OPTIONS = Object.freeze(${literal(optionDefaults.data)});\n${sets}\nexport const INTERNAL_COMPONENT_ATTRIBUTES = new Set(${literal(descriptors.filter((item) => item.attribute).map((item) => item.attribute))});\n${merge}\n// Resolve effective data options while preserving header and callback contracts\nexport const resolveDataOptionSettings = (localConfig = {}, globalConfig = {}) => ({${reads}});\n${readers}\n// END GENERATED DATA CONTRACT\n`,
    file = new URL('../src/runtime/config.js', import.meta.url);
let source = await readFile(file, 'utf8');
if (source.includes('// BEGIN GENERATED DATA CONTRACT'))
    source = source.replace(/\/\/ BEGIN GENERATED DATA CONTRACT[\s\S]*?\/\/ END GENERATED DATA CONTRACT\n?/, region);
else source += '\n' + region;
await writeFile(
    file,
    await format(source, {
        ...(await resolveConfig(file.pathname)),
        parser: 'babel',
    }),
);
const parse = descriptors
    // Select declarative controls with authored attributes
    .filter((item) => item.attribute || item.proxyAttribute)
    // Compile direct attribute reads from the authoritative descriptors
    .map((item) => {
        const attr = item.attribute || item.proxyAttribute,
            target = item.group ? `data.${item.group}` : `options.${item.setting}`,
            fallback = item.group
                ? `globalConfig.data?.${item.group} ?? DEFAULT_DATA_OPTIONS.${item.group}`
                : `globalConfig.${item.setting} ?? ${JSON.stringify(item.default)}`,
            value =
                item.parse === 'number'
                    ? `readNumberAttribute(element, '${attr}', ${fallback}, { min: ${item.validate === 'positiveInteger' ? 1 : 0} })`
                    : item.parse === 'boolean'
                      ? `readBooleanAttribute(element, '${attr}', ${fallback})`
                      : item.parse === 'json'
                        ? `parseJson(element.getAttribute('${attr}'), ${fallback})`
                        : `element.getAttribute('${attr}')`;
        return `if (element.hasAttribute('${attr}')) ${target} = ${value};`;
    })
    .join('\n');
await writeFile(
    new URL('../src/runtime/data-options.js', import.meta.url),
    await format(
        `// @license AlpineComponentLoader
// Copyright (c) LouisT
// Licensed under the MIT license in the repository root

// Generated by scripts/generate-data-contract.mjs
const suffix = new URL(import.meta.url).pathname.endsWith('.min.js') ? '.min.js' : '.js',
    importLocalModule = specifier => import(/* @vite-ignore */ specifier.replace(/\\.js$/, suffix)),
    [{ DEFAULT_DATA_OPTIONS, readBooleanAttribute, readNumberAttribute, validateDataOptions, resolveDataOptionSettings, DATA_FETCH_ATTRIBUTES, DATA_POLL_ATTRIBUTES, DATA_CACHE_BOUND_ATTRIBUTES, INTERNAL_COMPONENT_ATTRIBUTES }, { parseJson }] = await Promise.all([importLocalModule('./config.js'), importLocalModule('./values.js')]);
export { DEFAULT_DATA_OPTIONS, readBooleanAttribute, readNumberAttribute, resolveDataOptionSettings, DATA_FETCH_ATTRIBUTES, DATA_POLL_ATTRIBUTES, DATA_CACHE_BOUND_ATTRIBUTES, INTERNAL_COMPONENT_ATTRIBUTES };
// Preserve the data validator's diagnostic suffix contract
export const validateDataOptionSettings = (settings, suffix = '') => validateDataOptions(settings || {}, suffix + '.');
// Parse explicit declarative controls without shipping descriptor metadata
export const readDeclarativeOptionSettings = (element, globalConfig = {}) => {
    const data = {}, options = {};
    ${parse}
    if (Object.keys(data).length) options.data = data;
    return options;
};
`,
        {
            ...(await resolveConfig(file.pathname)),
            parser: 'babel',
        },
    ),
);
