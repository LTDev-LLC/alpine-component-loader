const generatedHeader = 'Generated by alpine-component-loader skeleton. Do not edit.',
    validModes = new Set(['css', 'manifest', 'both']),
    defaultViewports = {
        mobile: {
            width: 390,
            height: 844,
        },
        desktop: {
            width: 1440,
            height: 900,
        },
    };
let coverageSequence = 0;

const formatNumber = (value) => {
        // Format number
        return Number(value.toFixed(3)).toString();
    },
    cssDisplay = (value) => {
        // Run the css display operation
        return /^[a-z-]+$/.test(value || '') && value !== 'none' ? value : 'block';
    };

// Keep programmatic generation silent while allowing the CLI to expose useful milestones
const createProgressReporter = (callback) => (message) => {
    // Create progress reporter
    if (typeof callback !== 'function') return;
    // Guard the create progress reporter operation against runtime failures
    try {
        callback(message);
    } catch {
        // A display callback must never make capture fail
    }
};

const skeletonSelectors = (tagName, defaultComponentName) => {
    // Run the skeleton selectors operation
    return [`${tagName}:not(:defined)`, `${tagName}[aria-busy="true"]`, `${defaultComponentName}[tag="${tagName}"]`];
};

// Encode anonymous captured rectangles as a scalable alpha mask without authored DOM data
export const renderSkeletonMask = (variant) => {
    const height = Math.max(1, variant.height),
        rects = variant.blocks
            .map((block) => {
                // Transform the current item
                const x = block.x * 10,
                    width = block.width * 10,
                    rx = variant.width > 0 ? (block.radius / variant.width) * 1000 : 0;
                return `<rect x="${formatNumber(x)}" y="${formatNumber(block.y)}" width="${formatNumber(width)}" height="${formatNumber(block.height)}" rx="${formatNumber(rx)}" ry="${formatNumber(block.radius)}"/>`;
            })
            .join(''),
        svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 ${formatNumber(height)}" preserveAspectRatio="none">${rects}</svg>`;
    return `data:image/svg+xml,${encodeURIComponent(svg)}`;
};

const resolveBlockGeometry = (block, variant) => {
    // Resolve block geometry
    const pixelX = Number.isFinite(block.pixelX) ? block.pixelX : (variant.width * block.x) / 100,
        pixelWidth = Math.max(
            1,
            Number.isFinite(block.pixelWidth) ? block.pixelWidth : (variant.width * block.width) / 100,
        ),
        pixelEnd = Number.isFinite(block.pixelEnd) ? block.pixelEnd : variant.width - pixelX - pixelWidth,
        pixelHeight = Math.max(1, block.height),
        centered = Math.abs(pixelX - pixelEnd) <= 2,
        anchor = block.inlineAnchor || (centered ? 'center' : block.width >= 75 ? 'stretch' : 'start'),
        start = Math.max(0, pixelX),
        end = Math.max(0, pixelEnd);
    if (anchor === 'stretch')
        return {
            anchor,
            height: pixelHeight,
            position: `${formatNumber(start)}px ${formatNumber(block.y)}px`,
            size: `calc(100% - ${formatNumber(start)}px - ${formatNumber(end)}px) ${formatNumber(pixelHeight)}px`,
            start,
            end,
            width: null,
        };
    const position =
        anchor === 'center'
            ? `center ${formatNumber(block.y)}px`
            : anchor === 'end'
              ? `right ${formatNumber(end)}px top ${formatNumber(block.y)}px`
              : anchor === 'relative'
                ? `left ${formatNumber(block.x)}% top ${formatNumber(block.y)}px`
                : `${formatNumber(pixelX)}px ${formatNumber(block.y)}px`;
    return {
        anchor,
        height: pixelHeight,
        position,
        size: `${formatNumber(pixelWidth)}px ${formatNumber(pixelHeight)}px`,
        start: pixelX,
        end: pixelEnd,
        width: pixelWidth,
    };
};

// Use one mask layer per block so fixed-size and parent-anchored geometry stays stable
const renderSkeletonMaskTile = (block, geometry) => {
    const width = geometry.width || Math.max(1, block.pixelWidth || 1000),
        height = Math.max(1, geometry.height),
        rx = Math.min(500, (block.radius / width) * 1000),
        ry = Math.min(500, (block.radius / height) * 1000),
        svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" preserveAspectRatio="none"><rect width="1000" height="1000" rx="${formatNumber(rx)}" ry="${formatNumber(ry)}"/></svg>`;
    return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
};

const renderHostGeometry = (variant) => {
    // Render host geometry
    const capturedDisplay = cssDisplay(variant.display),
        display = capturedDisplay === 'inline' ? 'inline-block' : capturedDisplay,
        legacyFixed = !variant.inlineSizing && (capturedDisplay.startsWith('inline') || variant.constrainInlineSize),
        inlineSize =
            variant.inlineSizing === 'fill'
                ? 'inline-size:100%;'
                : variant.inlineSizing === 'layout'
                  ? 'inline-size:auto;'
                  : variant.inlineSizing === 'fixed' || legacyFixed
                    ? `inline-size:${formatNumber(variant.width)}px;`
                    : '',
        layout = variant.layout || {},
        marginValues = ['marginBlockStart', 'marginInlineEnd', 'marginBlockEnd', 'marginInlineStart'].map(
            // Transform the current item
            (property) => (Number.isFinite(layout[property]) ? layout[property] : 0),
        ),
        margin = marginValues.some(Boolean)
            ? `margin:${marginValues
                  .map(
                      // Transform the current item
                      (value) => `${formatNumber(value)}px`,
                  )
                  .join(' ')};`
            : '',
        alignSelf = ['start', 'end', 'center', 'stretch', 'baseline'].includes(layout.alignSelf)
            ? `align-self:${layout.alignSelf};`
            : '',
        justifySelf = ['start', 'end', 'center', 'stretch'].includes(layout.justifySelf)
            ? `justify-self:${layout.justifySelf};`
            : '',
        verticalAlign =
            display.startsWith('inline') && layout.verticalAlign && layout.verticalAlign !== 'baseline'
                ? `vertical-align:${layout.verticalAlign};`
                : '',
        position = ['relative', 'absolute', 'fixed', 'sticky'].includes(layout.position)
            ? `position:${layout.position};`
            : '',
        insets = position
            ? [
                  ['inset-block-start', layout.insetBlockStart],
                  ['inset-inline-end', layout.insetInlineEnd],
                  ['inset-block-end', layout.insetBlockEnd],
                  ['inset-inline-start', layout.insetInlineStart],
              ]
                  .filter(
                      // Select matching items
                      ([, value]) => Number.isFinite(value),
                  )
                  .map(
                      // Transform the current item
                      ([property, value]) => `${property}:${formatNumber(value)}px;`,
                  )
                  .join('')
            : '',
        height = formatNumber(variant.height);
    return `display:${display};box-sizing:border-box;block-size:${height}px;min-block-size:${height}px;min-inline-size:0;max-inline-size:100%;${inlineSize}${margin}${alignSelf}${justifySelf}${verticalAlign}${position}${insets}`;
};

const renderCssSkeletonRule = (tagName, variant, defaultComponentName) => {
    // Render css skeleton rule
    const selectors = skeletonSelectors(tagName, defaultComponentName).join(',\n'),
        geometries = variant.blocks.map(
            // Transform the current item
            (block) => resolveBlockGeometry(block, variant),
        ),
        masks = geometries.length
            ? geometries
                  .map(
                      // Transform the current item
                      (geometry, index) => renderSkeletonMaskTile(variant.blocks[index], geometry),
                  )
                  .join(',')
            : 'none',
        positions = geometries.length
            ? geometries
                  .map(
                      // Transform the current item
                      (geometry) => geometry.position,
                  )
                  .join(',')
            : '0 0',
        sizes = geometries.length
            ? geometries
                  .map(
                      // Transform the current item
                      (geometry) => geometry.size,
                  )
                  .join(',')
            : 'auto',
        hostGeometry = renderHostGeometry(variant);
    return `${selectors}{--acl-skeleton-mask:${masks};--acl-skeleton-mask-position:${positions};--acl-skeleton-mask-size:${sizes};${hostGeometry}overflow:hidden;color:transparent!important;background-color:var(--acl-skeleton-base,#e5e7eb);background-image:linear-gradient(100deg,transparent 32%,var(--acl-skeleton-highlight,rgba(255,255,255,.72)) 50%,transparent 68%);background-size:200% 100%;background-position:200% 0;background-repeat:no-repeat;-webkit-mask-image:var(--acl-skeleton-mask);-webkit-mask-position:var(--acl-skeleton-mask-position);-webkit-mask-size:var(--acl-skeleton-mask-size);-webkit-mask-repeat:no-repeat;-webkit-mask-origin:border-box;-webkit-mask-clip:border-box;mask-image:var(--acl-skeleton-mask);mask-mode:alpha;mask-position:var(--acl-skeleton-mask-position);mask-size:var(--acl-skeleton-mask-size);mask-repeat:no-repeat;mask-origin:border-box;mask-clip:border-box;animation:acl-skeleton-css-shimmer 1.5s linear infinite}`;
};

// Render a standalone stylesheet that paints skeletons before loader JavaScript executes
export const renderCssSkeletons = (captures, breakpoint = 768, defaultComponentName = 'acl-component') => {
    const desktopRules = [],
        mobileRules = [],
        hiddenChildren = [],
        reducedMotionSelectors = [];
    Array.from(captures.keys())
        .sort()
        .forEach((tagName) => {
            // Process the current item
            const variants = captures.get(tagName),
                desktop = variants.desktop || variants.mobile,
                mobile = variants.mobile || variants.desktop,
                selectors = skeletonSelectors(tagName, defaultComponentName);
            desktopRules.push(renderCssSkeletonRule(tagName, desktop, defaultComponentName));
            mobileRules.push(renderCssSkeletonRule(tagName, mobile, defaultComponentName));
            hiddenChildren.push(
                ...selectors.map(
                    // Transform the current item
                    (selector) => `${selector}>*`,
                ),
            );
            reducedMotionSelectors.push(...selectors);
        });
    return `/* ${generatedHeader} */\n@keyframes acl-skeleton-css-shimmer{from{background-position:200% 0}to{background-position:-200% 0}}\n${desktopRules.join('\n')}\n${hiddenChildren.join(',\n')}{visibility:hidden!important}\n@media(max-width:${Math.max(0, breakpoint - 1)}px){\n${mobileRules.join('\n')}\n}\n@media(prefers-reduced-motion:reduce){\n${reducedMotionSelectors.join(',\n')}{animation:none;background-position:0 0}\n}\n`;
};

// Convert captured anonymous rectangles into one responsive, self-contained loading fragment
export const renderSkeletonHtml = (variants, breakpoint = 768) => {
    const mobile = variants.mobile || variants.desktop,
        desktop = variants.desktop || variants.mobile;
    if (!mobile || !desktop) throw new TypeError('At least one skeleton viewport capture is required.');
    // Render the captured blocks for one responsive variant
    const blocks = (variant) =>
        variant.blocks
            .map((block) => {
                // Transform the current item
                const geometry = resolveBlockGeometry(block, variant),
                    inline =
                        geometry.anchor === 'stretch'
                            ? `inset-inline-start:${formatNumber(geometry.start)}px;inset-inline-end:${formatNumber(geometry.end)}px;`
                            : geometry.anchor === 'center'
                              ? 'inset-inline-start:50%;transform:translateX(-50%);'
                              : geometry.anchor === 'end'
                                ? `inset-inline-end:${formatNumber(geometry.end)}px;`
                                : geometry.anchor === 'relative'
                                  ? `inset-inline-start:${formatNumber(block.x)}%;`
                                  : `inset-inline-start:${formatNumber(geometry.start)}px;`,
                    width = geometry.width == null ? '' : `inline-size:${formatNumber(geometry.width)}px;`;
                return `<span class="acl-generated-skeleton__block" style="${inline}inset-block-start:${formatNumber(block.y)}px;${width}block-size:${formatNumber(geometry.height)}px;border-radius:${formatNumber(block.radius)}px"></span>`;
            })
            .join('');
    return `<div class="acl-generated-skeleton" role="presentation" aria-hidden="true"><style>
.acl-generated-skeleton{display:block;inline-size:100%;pointer-events:none}
.acl-generated-skeleton__variant{position:relative;display:block;inline-size:100%;overflow:hidden;background:var(--acl-skeleton-surface,transparent)}
.acl-generated-skeleton__variant--mobile{display:none}
.acl-generated-skeleton__block{position:absolute;background:var(--acl-skeleton-base,#e5e7eb)}
.acl-generated-skeleton__variant::after{content:"";position:absolute;inset:0;transform:translateX(-100%);background:linear-gradient(90deg,transparent,var(--acl-skeleton-highlight,rgba(255,255,255,.55)),transparent);animation:acl-skeleton-shimmer 1.5s infinite}
@keyframes acl-skeleton-shimmer{to{transform:translateX(100%)}}
@media(max-width:${Math.max(0, breakpoint - 1)}px){.acl-generated-skeleton__variant--desktop{display:none}.acl-generated-skeleton__variant--mobile{display:block}}
@media(prefers-reduced-motion:reduce){.acl-generated-skeleton__variant::after{animation:none;display:none}}
</style><div class="acl-generated-skeleton__variant acl-generated-skeleton__variant--desktop" style="block-size:${formatNumber(desktop.height)}px">${blocks(desktop)}</div><div class="acl-generated-skeleton__variant acl-generated-skeleton__variant--mobile" style="block-size:${formatNumber(mobile.height)}px">${blocks(mobile)}</div></div>`;
};

// Serialize inline skeleton HTML as an importable ES module in stable tag order
export const renderSkeletonManifest = (captures, breakpoint = 768) => {
    const skeletons = {};
    Array.from(captures.keys())
        .sort()
        .forEach((tagName) => {
            // Process the current item
            skeletons[tagName] = { html: renderSkeletonHtml(captures.get(tagName), breakpoint) };
        });
    return `// ${generatedHeader}\nconst manifest = ${JSON.stringify(
        {
            version: 1,
            skeletons,
        },
        null,
        2,
    )};\n\nexport default manifest;\n`;
};

const reservationRule = (tagName, variant, defaultComponentName) => {
    // Run the reservation rule operation
    return `${tagName}:not(:defined),\n${tagName}[aria-busy="true"],\n${defaultComponentName}[tag="${tagName}"]{${renderHostGeometry(variant)}overflow:hidden}`;
};

// Reserve captured host geometry from the first stylesheet pass through component readiness
export const renderReservationCss = (captures, breakpoint = 768, defaultComponentName = 'acl-component') => {
    const desktop = [],
        mobile = [];
    Array.from(captures.keys())
        .sort()
        .forEach((tagName) => {
            // Process the current item
            const variants = captures.get(tagName),
                desktopVariant = variants.desktop || variants.mobile,
                mobileVariant = variants.mobile || variants.desktop;
            desktop.push(reservationRule(tagName, desktopVariant, defaultComponentName));
            mobile.push(reservationRule(tagName, mobileVariant, defaultComponentName));
        });
    return `/* ${generatedHeader} */\n${desktop.join('\n')}\n@media(max-width:${Math.max(0, breakpoint - 1)}px){\n${mobile.join('\n')}\n}\n`;
};

const assertSafeGeneratedTarget = async (path, force) => {
    // Run the assert safe generated target operation
    try {
        const existing = await readFile(path, 'utf8'),
            isGenerated =
                existing.startsWith(`// ${generatedHeader}`) || existing.startsWith(`/* ${generatedHeader} */`);
        if (!force && !isGenerated)
            throw new TypeError(`Refusing to overwrite non-generated file: ${path}. Pass --force to replace it.`);
    } catch (error) {
        if (error?.code !== 'ENOENT') throw error;
    }
};

const atomicWrite = async (path, content) => {
    // Run the atomic write operation
    const temporaryPath = `${path}.${process.pid}.tmp`;
    // Guard the atomic write operation against runtime failures
    try {
        await writeFile(temporaryPath, content, 'utf8');
        await rename(temporaryPath, path);
    } catch (error) {
        await unlink(temporaryPath).catch(() => {
            // Ignore cleanup failures while preserving the original write error
        });
        throw error;
    }
};

// Write the deterministic generated module and reservation stylesheet together
export const writeSkeletonArtifacts = async ({
    captures,
    outDir,
    breakpoint,
    defaultComponentName,
    mode = 'css',
    force = false,
}) => {
    if (!validModes.has(mode)) throw new TypeError(`Unsupported skeleton mode "${mode}".`);
    const directory = resolve(outDir),
        cssSkeletonPath = join(directory, 'acl-skeletons.css'),
        manifestPath = join(directory, 'acl-skeletons.generated.js'),
        manifestCssPath = join(directory, 'acl-skeletons.generated.css'),
        artifacts = [];
    if (mode === 'css' || mode === 'both')
        artifacts.push({
            kind: 'css',
            path: cssSkeletonPath,
            content: renderCssSkeletons(captures, breakpoint, defaultComponentName),
        });
    if (mode === 'manifest' || mode === 'both') {
        artifacts.push({
            kind: 'manifest',
            path: manifestPath,
            content: renderSkeletonManifest(captures, breakpoint),
        });
        artifacts.push({
            kind: 'manifest-css',
            path: manifestCssPath,
            content: renderReservationCss(captures, breakpoint, defaultComponentName),
        });
    }
    await mkdir(directory, { recursive: true });
    await Promise.all(
        artifacts.map(
            // Transform the current item
            (artifact) => assertSafeGeneratedTarget(artifact.path, force),
        ),
    );
    await Promise.all(
        artifacts.map(
            // Transform the current item
            (artifact) => atomicWrite(artifact.path, artifact.content),
        ),
    );
    return {
        mode,
        files: artifacts.map(
            // Transform the current item
            (artifact) => artifact.path,
        ),
        cssSkeletonPath: artifacts.some(
            // Check the current item
            (artifact) => artifact.kind === 'css',
        )
            ? cssSkeletonPath
            : null,
        manifestPath: artifacts.some(
            // Check the current item
            (artifact) => artifact.kind === 'manifest',
        )
            ? manifestPath
            : null,
        manifestCssPath: artifacts.some(
            // Check the current item
            (artifact) => artifact.kind === 'manifest-css',
        )
            ? manifestCssPath
            : null,
    };
};

const loadBrowserType = async (providedBrowserType) => {
    // Load browser type
    if (providedBrowserType) return providedBrowserType;
    // Guard the load browser type operation against runtime failures
    try {
        return (await import('playwright')).chromium;
    } catch (error) {
        if (error?.code === 'ERR_MODULE_NOT_FOUND')
            throw new Error(
                'Playwright is required for skeleton generation. Install it with "npm install --save-dev playwright", then run "npx playwright install chromium".',
            );
        throw error;
    }
};

// Capture every ready loader component on one route without returning authored content
const captureReadyComponents = async (page, { include, exclude, maxBlocks }) =>
    page.evaluate(
        ({ includeTags, excludeTags, blockLimit }) => {
            // Read the browser state
            const includeSet = new Set(includeTags),
                excludeSet = new Set(excludeTags),
                visible = (element) => {
                    const style = getComputedStyle(element),
                        rect = element.getBoundingClientRect();
                    return (
                        style.display !== 'none' &&
                        style.visibility !== 'hidden' &&
                        Number(style.opacity) !== 0 &&
                        rect.width > 0 &&
                        rect.height > 0
                    );
                },
                selected = Array.from(document.querySelectorAll('[data-acl-component]')).filter(
                    // Select matching items
                    (element) =>
                        visible(element) &&
                        element._state === 'ready' &&
                        (!includeSet.size || includeSet.has(element.localName)) &&
                        !excludeSet.has(element.localName),
                ),
                firstByTag = new Map();
            selected.forEach((element) => {
                // Process the current item
                if (!firstByTag.has(element.localName)) firstByTag.set(element.localName, element);
            });

            const captures = {};
            // Process each entry
            for (const [tagName, host] of firstByTag) {
                const hostRect = host.getBoundingClientRect(),
                    hostStyle = getComputedStyle(host),
                    rawBlocks = [],
                    parentRect = host.parentElement?.getBoundingClientRect(),
                    parentStyle = host.parentElement ? getComputedStyle(host.parentElement) : null,
                    parentInlineSize = parentRect
                        ? parentRect.width -
                          (Number.parseFloat(parentStyle.paddingLeft) || 0) -
                          (Number.parseFloat(parentStyle.paddingRight) || 0)
                        : innerWidth,
                    fillsParent = Math.abs(hostRect.width - parentInlineSize) <= 2,
                    parentManagesInlineSize = /(?:grid|flex)/.test(parentStyle?.display || ''),
                    ignoredTags = new Set(['SCRIPT', 'STYLE', 'TEMPLATE', 'NOSCRIPT']),
                    replacedTags = new Set([
                        'IMG',
                        'VIDEO',
                        'CANVAS',
                        'SVG',
                        'IFRAME',
                        'INPUT',
                        'TEXTAREA',
                        'SELECT',
                        'BUTTON',
                        'PROGRESS',
                        'METER',
                    ]),
                    clip = (rect) => {
                        // Run the clip operation
                        const left = Math.max(hostRect.left, rect.left),
                            top = Math.max(hostRect.top, rect.top),
                            right = Math.min(hostRect.right, rect.right),
                            bottom = Math.min(hostRect.bottom, rect.bottom);
                        if (right - left < 2 || bottom - top < 2) return null;
                        return {
                            left,
                            top,
                            width: right - left,
                            height: bottom - top,
                        };
                    },
                    radiusFor = (style, rect, text = false) => {
                        // Run the radius for operation
                        if (text) return Math.min(4, rect.height / 2);
                        const value = style.borderRadius || '0';
                        if (value.includes('%')) return Math.min(rect.width, rect.height) / 2;
                        return Math.max(
                            0,
                            Math.min(Number.parseFloat(value) || 0, Math.min(rect.width, rect.height) / 2),
                        );
                    },
                    addBlock = (rect, radius, priority = 1, kind = 'surface') => {
                        // Add block
                        const clipped = clip(rect);
                        if (!clipped) return;
                        rawBlocks.push({
                            ...clipped,
                            radius,
                            priority,
                            kind,
                            rawLeft: rect.left,
                            rawTop: rect.top,
                            rawWidth: rect.width,
                            rawHeight: rect.height,
                        });
                    },
                    walk = (node) => {
                        // Walk
                        if (node.nodeType === Node.TEXT_NODE) {
                            if (!node.textContent.trim()) return;
                            const range = document.createRange();
                            range.selectNodeContents(node);
                            Array.from(range.getClientRects()).forEach(
                                // Process the current item
                                (rect) => addBlock(rect, radiusFor({}, rect, true), 3, 'text'),
                            );
                            range.detach?.();
                            return;
                        }
                        if (node.nodeType !== Node.ELEMENT_NODE || ignoredTags.has(node.tagName)) return;
                        const style = getComputedStyle(node);
                        if (!visible(node)) return;
                        const rect = node.getBoundingClientRect(),
                            children = node.shadowRoot
                                ? Array.from(node.shadowRoot.childNodes)
                                : node.tagName === 'SLOT'
                                  ? node.assignedNodes({ flatten: true })
                                  : Array.from(node.childNodes);
                        if (replacedTags.has(node.tagName)) addBlock(rect, radiusFor(style, rect), 4, 'replaced');
                        else {
                            const backgroundVisible =
                                    style.backgroundImage !== 'none' ||
                                    !['rgba(0, 0, 0, 0)', 'transparent'].includes(style.backgroundColor),
                                borderVisible = ['Top', 'Right', 'Bottom', 'Left'].some(
                                    // Check the current item
                                    (side) =>
                                        Number.parseFloat(style[`border${side}Width`]) > 0 &&
                                        style[`border${side}Style`] !== 'none',
                                );
                            if (
                                (backgroundVisible || borderVisible) &&
                                children.length === 0 &&
                                rect.width * rect.height < hostRect.width * hostRect.height * 0.8
                            )
                                addBlock(rect, radiusFor(style, rect), 2, 'surface');
                        }
                        children.forEach(walk);
                    },
                    root = host.shadowRoot || host;
                Array.from(root.childNodes).forEach(walk);
                const unique = [];
                rawBlocks
                    .sort(
                        // Compare the current items
                        (a, b) => b.priority - a.priority || b.width * b.height - a.width * a.height,
                    )
                    .forEach((block) => {
                        // Process the current item
                        const duplicate = unique.some((existing) => {
                            // Check the current item
                            const left = Math.max(block.left, existing.left),
                                top = Math.max(block.top, existing.top),
                                right = Math.min(block.left + block.width, existing.left + existing.width),
                                bottom = Math.min(block.top + block.height, existing.top + existing.height),
                                intersection = Math.max(0, right - left) * Math.max(0, bottom - top),
                                smaller = Math.min(block.width * block.height, existing.width * existing.height);
                            return smaller > 0 && intersection / smaller > 0.92;
                        });
                        if (!duplicate && unique.length < blockLimit) unique.push(block);
                    });
                unique.sort(
                    // Compare the current items
                    (a, b) => a.top - b.top || a.left - b.left,
                );
                const rounded = (value) => {
                        // Run the rounded operation
                        return Math.round(value * 2) / 2;
                    },
                    numericStyle = (property) => {
                        // Run the numeric style operation
                        const value = Number.parseFloat(hostStyle[property]);
                        return Number.isFinite(value) ? rounded(value) : null;
                    };
                captures[tagName] = {
                    display: hostStyle.display,
                    width: rounded(hostRect.width),
                    height: rounded(hostRect.height),
                    inlineSizing: fillsParent ? 'fill' : parentManagesInlineSize ? 'layout' : 'fixed',
                    constrainInlineSize: !fillsParent && !parentManagesInlineSize,
                    layout: {
                        marginBlockStart: numericStyle('marginTop'),
                        marginInlineEnd: numericStyle('marginRight'),
                        marginBlockEnd: numericStyle('marginBottom'),
                        marginInlineStart: numericStyle('marginLeft'),
                        alignSelf: hostStyle.alignSelf,
                        justifySelf: hostStyle.justifySelf,
                        verticalAlign: hostStyle.verticalAlign,
                        position: hostStyle.position,
                        insetBlockStart: numericStyle('top'),
                        insetInlineEnd: numericStyle('right'),
                        insetBlockEnd: numericStyle('bottom'),
                        insetInlineStart: numericStyle('left'),
                    },
                    blocks: unique.map((block) => {
                        // Transform the current item
                        const pixelX = block.rawLeft - hostRect.left,
                            pixelEnd = hostRect.right - (block.rawLeft + block.rawWidth),
                            centered = Math.abs(pixelX - pixelEnd) <= 2,
                            edgeThreshold = Math.max(24, hostRect.width * 0.08),
                            stretch =
                                block.kind !== 'text' &&
                                block.rawWidth / hostRect.width >= 0.75 &&
                                pixelX >= -1 &&
                                pixelEnd >= -1,
                            inlineAnchor = stretch
                                ? 'stretch'
                                : centered
                                  ? 'center'
                                  : pixelX >= -1 && pixelX <= edgeThreshold
                                    ? 'start'
                                    : pixelEnd >= -1 && pixelEnd <= edgeThreshold
                                      ? 'end'
                                      : 'relative';
                        return {
                            x: Math.round(((block.left - hostRect.left) / hostRect.width) * 100 * 1000) / 1000,
                            y: rounded(block.rawTop - hostRect.top),
                            width: Math.round((block.width / hostRect.width) * 100 * 1000) / 1000,
                            height: rounded(block.rawHeight),
                            radius: rounded(block.radius),
                            pixelX: rounded(pixelX),
                            pixelEnd: rounded(pixelEnd),
                            pixelWidth: rounded(block.rawWidth),
                            inlineAnchor,
                        };
                    }),
                };
            }
            return captures;
        },
        {
            includeTags: include,
            excludeTags: exclude,
            blockLimit: maxBlocks,
        },
    );

const settleRoute = async (page, timeout, include, exclude, report) => {
    // Settle route
    report('Disabling animations and activating deferred components...');
    await page.addStyleTag({
        content:
            '*,*::before,*::after{animation-duration:0s!important;animation-delay:0s!important;transition:none!important;caret-color:transparent!important}',
    });
    await page.evaluate(async () => {
        // Read the browser state
        const step = Math.max(200, Math.floor(innerHeight * 0.75));
        // Iterate over the indexed values
        for (let y = 0; y < document.documentElement.scrollHeight; y += step) {
            scrollTo(0, y);
            await new Promise(
                // Settle the asynchronous operation
                (resolvePromise) => setTimeout(resolvePromise, 25),
            );
        }
        scrollTo(0, 0);
        await document.fonts?.ready;
        document.getAnimations?.({ subtree: true }).forEach(
            // Settle route
            (animation) => animation.pause(),
        );
        await new Promise(
            // Settle the asynchronous operation
            (resolvePromise) =>
                requestAnimationFrame(
                    // Run the scheduled animation task
                    () => requestAnimationFrame(resolvePromise),
                ),
        );
    });
    const registration = await page.evaluate(
        ({ includeTags, excludeTags }) => {
            // Discover custom-element hosts before asynchronous modules necessarily register them
            const includeSet = new Set(includeTags),
                excludeSet = new Set(excludeTags),
                candidates = Array.from(document.querySelectorAll('*')).filter(
                    // Select custom-element hosts that skeleton capture may consume
                    (element) =>
                        element.localName.includes('-') &&
                        (!includeSet.size || includeSet.has(element.localName)) &&
                        !excludeSet.has(element.localName),
                ),
                tags = Array.from(
                    new Set(
                        candidates.map(
                            // Transform the current item
                            (element) => element.localName,
                        ),
                    ),
                );
            return {
                tags,
                stateful: candidates.some(
                    // Check whether a visible loader host is already available
                    (element) => {
                        const style = getComputedStyle(element);
                        return (
                            element.matches('[data-acl-component]') &&
                            style.display !== 'none' &&
                            style.visibility !== 'hidden' &&
                            typeof element._state === 'string'
                        );
                    },
                ),
            };
        },
        {
            includeTags: include,
            excludeTags: exclude,
        },
    );
    if (!registration.stateful) {
        const registrationTimeout = Math.min(Math.max(timeout, 1), 5_000),
            candidateDetail = registration.tags.length
                ? ` of ${registration.tags.length} initial custom element type${registration.tags.length === 1 ? '' : 's'}`
                : ' after the initial document scan';
        report(`Waiting up to ${registrationTimeout}ms for asynchronous registration${candidateDetail}...`);
        // A module may register or insert its first component after DOMContentLoaded
        try {
            await page.waitForFunction(
                // Check whether a matching visible host has acquired loader lifecycle state
                ({ includeTags, excludeTags }) => {
                    const includeSet = new Set(includeTags),
                        excludeSet = new Set(excludeTags);
                    return Array.from(document.querySelectorAll('[data-acl-component]')).some((element) => {
                        // Select one capturable loader host regardless of whether it existed during the initial scan
                        const style = getComputedStyle(element);
                        return (
                            (!includeSet.size || includeSet.has(element.localName)) &&
                            !excludeSet.has(element.localName) &&
                            style.display !== 'none' &&
                            style.visibility !== 'hidden' &&
                            typeof element._state === 'string'
                        );
                    });
                },
                {
                    includeTags: include,
                    excludeTags: exclude,
                },
                { timeout: registrationTimeout },
            );
        } catch {
            report('Component registration grace period elapsed.');
        }
    }
    const discovery = await page.evaluate(
            ({ includeTags, excludeTags }) => {
                // Read the browser state
                const includeSet = new Set(includeTags),
                    excludeSet = new Set(excludeTags),
                    visibleElements = Array.from(document.querySelectorAll('[data-acl-component]')).filter(
                        (element) => {
                            // Select matching items
                            const style = getComputedStyle(element);
                            return (
                                style.display !== 'none' &&
                                style.visibility !== 'hidden' &&
                                (!includeSet.size || includeSet.has(element.localName)) &&
                                !excludeSet.has(element.localName)
                            );
                        },
                    ),
                    tags = Array.from(
                        new Set(
                            visibleElements
                                .filter(
                                    // Select matching items
                                    (element) => typeof element._state === 'string',
                                )
                                .map(
                                    // Transform the current item
                                    (element) => element.localName,
                                ),
                        ),
                    ),
                    tagSet = new Set(tags),
                    skipped = Array.from(
                        new Set(
                            visibleElements
                                .filter(
                                    // Select matching items
                                    (element) => typeof element._state !== 'string' && !tagSet.has(element.localName),
                                )
                                .map(
                                    // Transform the current item
                                    (element) => element.localName,
                                ),
                        ),
                    );
                return {
                    tags,
                    skipped,
                };
            },
            {
                includeTags: include,
                excludeTags: exclude,
            },
        ),
        { tags, skipped } = discovery;
    let capturableTags = tags;
    if (skipped.length)
        report(
            `Ignoring ${skipped.length} non-capturable wrapper type${skipped.length === 1 ? '' : 's'}: ${skipped
                .map(
                    // Transform the current item
                    (tag) => `<${tag}>`,
                )
                .join(', ')}.`,
        );
    if (tags.length) {
        const activated = await page.evaluate(async (expectedTags) => {
            // Visit deferred hosts after registration so their observers see a real intersection
            let count = 0;
            // Activate one deferred host for each component type
            for (const tagName of expectedTags) {
                const element = Array.from(document.querySelectorAll(tagName)).find(
                    // Select one deferred instance for each component type
                    (candidate) => candidate._state === 'deferred',
                );
                if (!element) continue;
                element.scrollIntoView({
                    block: 'center',
                    inline: 'nearest',
                });
                await new Promise(
                    // Give intersection observers and scheduled loading work a rendering turn
                    (resolvePromise) =>
                        requestAnimationFrame(
                            // Finish after the intersection observer has a chance to schedule loading
                            () => {
                                setTimeout(resolvePromise, 50);
                            },
                        ),
                );
                count++;
            }
            scrollTo(0, 0);
            return count;
        }, tags);
        if (activated)
            report(`Activated ${activated} deferred component type${activated === 1 ? '' : 's'} after registration.`);
        report(`Waiting for ${tags.length} component type${tags.length === 1 ? '' : 's'} to become ready...`);
        // Guard the settle route operation against runtime failures
        try {
            await page.waitForFunction(
                // Check whether the expected browser state is ready
                (expectedTags) =>
                    expectedTags.every(
                        // Check every item
                        (tagName) =>
                            Array.from(document.querySelectorAll(tagName)).some(
                                // Check the current item
                                (element) => element._state === 'ready',
                            ),
                    ),
                tags,
                { timeout },
            );
        } catch (error) {
            const pending = await page.evaluate(
                    // Read the browser state
                    (expectedTags) =>
                        expectedTags.flatMap((tagName) => {
                            // Expand the current item
                            const elements = Array.from(document.querySelectorAll(tagName));
                            if (
                                elements.some(
                                    // Check the current item
                                    (element) => element._state === 'ready',
                                )
                            )
                                return [];
                            const states = Array.from(
                                new Set(
                                    elements.map(
                                        // Transform the current item
                                        (element) => element._state || 'unset',
                                    ),
                                ),
                            );
                            return [
                                {
                                    tagName,
                                    states,
                                },
                            ];
                        }),
                    tags,
                ),
                detail = pending.length
                    ? ` Still waiting for ${pending
                          .map(
                              // Transform the current item
                              (item) => `<${item.tagName}> (${item.states.join(', ')})`,
                          )
                          .join(', ')}.`
                    : '';
            throw new Error(`${error.message}${detail}`, { cause: error });
        }
        report(`All ${tags.length} component type${tags.length === 1 ? '' : 's'} reached ready state.`);
        capturableTags = await page.evaluate(
            // Retain only ready hosts with layout that captureReadyComponents can consume
            (expectedTags) =>
                expectedTags.filter(
                    // Select component types with at least one capturable instance
                    (tagName) =>
                        Array.from(document.querySelectorAll(tagName)).some((element) => {
                            // Check whether the current instance has stable capturable layout
                            const style = getComputedStyle(element),
                                rect = element.getBoundingClientRect();
                            return (
                                element._state === 'ready' &&
                                style.display !== 'none' &&
                                style.visibility !== 'hidden' &&
                                Number(style.opacity) !== 0 &&
                                rect.width > 0 &&
                                rect.height > 0
                            );
                        }),
                ),
            tags,
        );
        const layoutlessCount = tags.length - capturableTags.length;
        if (layoutlessCount)
            report(
                `Ignoring ${layoutlessCount} ready component type${layoutlessCount === 1 ? '' : 's'} without capturable layout.`,
            );
    } else report('No visible stateful components were discovered on this route.');
    return capturableTags;
};

const resolveRouteUrls = (baseUrl, routes) => {
    // Resolve route urls
    return routes.length
        ? routes.map(
              // Transform the current item
              (route) => new URL(route, baseUrl).toString(),
          )
        : [baseUrl];
};

// Orchestrate responsive route capture and produce the generated skeleton artifacts
export const generateSkeletons = async (options, dependencies = {}) => {
    const report = createProgressReporter(dependencies.onProgress);
    report('Loading the Playwright browser driver...');
    const browserType = await loadBrowserType(dependencies.browserType || dependencies.chromium),
        browserName = browserType.name?.() || 'chromium',
        browserLabel = browserName.charAt(0).toUpperCase() + browserName.slice(1),
        captures = new Map(),
        warnings = [],
        failures = [],
        include = options.include || [],
        exclude = options.exclude || [],
        viewports = options.viewports || defaultViewports;
    let server = null,
        browser = null;
    // Guard the generate skeletons operation against runtime failures
    try {
        let baseUrl;
        if (options.target.type === 'local') {
            report(`Starting a temporary server for ${options.target.root}...`);
            server = await startACLDevServer({
                root: options.target.root,
                index: options.target.index,
                host: '127.0.0.1',
                port: 0,
                watchFiles: false,
                injectAllHtml: true,
            });
            baseUrl = server.url;
            report(`Temporary server ready at ${baseUrl}.`);
        } else {
            baseUrl = options.target.url;
            report(`Using remote target ${baseUrl}.`);
        }

        report(`Launching headless ${browserLabel}...`);
        // Guard the generate skeletons operation against runtime failures
        try {
            browser = await browserType.launch({ headless: true });
        } catch (error) {
            throw new Error(
                `${browserLabel} could not start. Run "npx playwright install ${browserName}". ${error.message}`,
            );
        }
        const routeUrls = resolveRouteUrls(baseUrl, options.routes || []),
            discovered = new Set();
        report(
            `Capturing ${routeUrls.length} route${routeUrls.length === 1 ? '' : 's'} at ${Object.keys(viewports).length} viewport${Object.keys(viewports).length === 1 ? '' : 's'}.`,
        );
        // Process each entry
        for (const [viewportName, viewport] of Object.entries(viewports)) {
            // Process each route url
            for (const routeUrl of routeUrls) {
                const captureLabel = `${viewportName} ${viewport.width}x${viewport.height}`;
                report(`[${captureLabel}] Loading ${routeUrl}...`);
                const page = await browser.newPage({
                        viewport,
                        bypassCSP: true,
                        reducedMotion: 'reduce',
                    }),
                    coverageDirectory = process.env.ACL_BROWSER_COVERAGE_DIR;
                await dependencies.preparePage?.(page, {
                    routeUrl,
                    viewport,
                    viewportName,
                });
                if (coverageDirectory && page.coverage?.startJSCoverage)
                    await page.coverage.startJSCoverage({
                        resetOnNavigation: false,
                        reportAnonymousScripts: true,
                    });
                // Guard the generate skeletons operation against runtime failures
                try {
                    await page.goto(routeUrl, {
                        waitUntil: 'domcontentloaded',
                        timeout: options.timeout,
                    });
                    report(`[${captureLabel}] DOM loaded.`);
                    let routeTags = [];
                    // Guard the generate skeletons operation against runtime failures
                    try {
                        routeTags = await settleRoute(page, options.timeout, include, exclude, (message) => {
                            // Settle the routed operation
                            return report(`[${captureLabel}] ${message}`);
                        });
                    } catch (error) {
                        failures.push(`${viewportName} ${routeUrl}: ${error.message}`);
                        report(`[${captureLabel}] Readiness wait failed: ${error.message}`);
                        report(`[${captureLabel}] Capturing components that are ready now.`);
                    }
                    routeTags.forEach(
                        // Process the current item
                        (tag) => discovered.add(tag),
                    );
                    const pageCaptures = await captureReadyComponents(page, {
                        include,
                        exclude,
                        maxBlocks: options.maxBlocks || 256,
                    });
                    Object.entries(pageCaptures).forEach(([tagName, capture]) => {
                        // Process the current item
                        const variants = captures.get(tagName) || {};
                        if (!variants[viewportName]) variants[viewportName] = capture;
                        else warnings.push(`Ignored another <${tagName}> instance for ${viewportName} on ${routeUrl}.`);
                        captures.set(tagName, variants);
                    });
                    const captureCount = Object.keys(pageCaptures).length;
                    report(
                        `[${captureLabel}] Captured ${captureCount} component type${captureCount === 1 ? '' : 's'}.`,
                    );
                } catch (error) {
                    failures.push(`${viewportName} ${routeUrl}: ${error.message}`);
                    report(`[${captureLabel}] Capture failed: ${error.message}`);
                } finally {
                    if (coverageDirectory && page.coverage?.stopJSCoverage) {
                        const coverage = await page.coverage.stopJSCoverage();
                        await mkdir(coverageDirectory, { recursive: true });
                        await writeFile(
                            resolve(coverageDirectory, `skeleton-${process.pid}-${coverageSequence++}.json`),
                            JSON.stringify(coverage),
                        );
                    }
                    await page.close();
                }
            }
        }

        include
            .filter(
                // Select matching items
                (tag) => !captures.has(tag),
            )
            .forEach(
                // Process the current item
                (tag) => failures.push(`Included component <${tag}> was not captured.`),
            );
        Array.from(discovered)
            .filter(
                // Select matching items
                (tag) => !exclude.includes(tag) && (!include.length || include.includes(tag)) && !captures.has(tag),
            )
            .forEach(
                // Process the current item
                (tag) => failures.push(`Component <${tag}> never reached a capturable ready state.`),
            );
        captures.forEach((variants, tagName) => {
            // Process the current item
            if (!variants.mobile || !variants.desktop)
                warnings.push(`<${tagName}> was missing one responsive capture; reused the available variant.`);
        });
        if (!captures.size && failures.length)
            throw new Error(
                `Skeleton capture failed:\n${failures
                    .map(
                        // Transform the current item
                        (failure) => `- ${failure}`,
                    )
                    .join('\n')}`,
            );
        if (!captures.size) throw new Error('No ready Alpine Component Loader components were captured.');
        if (failures.length && !options.allowPartial)
            throw new Error(
                `Skeleton capture failed:\n${failures
                    .map(
                        // Transform the current item
                        (failure) => `- ${failure}`,
                    )
                    .join('\n')}`,
            );

        report(
            `Writing ${options.mode || 'css'} skeleton artifacts for ${captures.size} component type${captures.size === 1 ? '' : 's'}...`,
        );
        const files = await writeSkeletonArtifacts({
            captures,
            outDir: options.outDir,
            breakpoint: options.breakpoint,
            defaultComponentName: options.defaultComponentName || 'acl-component',
            mode: options.mode || 'css',
            force: options.force,
        });
        report(`Wrote ${files.files.length} generated file${files.files.length === 1 ? '' : 's'}.`);
        return {
            ...files,
            components: Array.from(captures.keys()).sort(),
            failures,
            warnings,
            target: options.target.type === 'local' ? basename(options.target.root) : options.target.url,
        };
    } finally {
        if (browser || server) report('Closing capture resources...');
        await browser?.close().catch(() => {
            // Ignore browser cleanup failures after capture
        });
        await server?.close().catch(() => {
            // Ignore server cleanup failures after capture
        });
    }
};
